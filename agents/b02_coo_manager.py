def susun_jadwal(tugas):
    """Draf jadwal harian COO: tugas dibagi ke slot 06.00–21.00 (slot template, bukan jadwal otomatis)."""
    slot = ["06.00", "07.00", "08.00", "09.00", "11.00", "13.00", "14.00",
            "15.00", "17.00", "19.00", "20.00", "21.00"]
    draf = _draf_dasar("jadwal_harian", "Jadwal harian — {}".format(date.today().isoformat()))
    daftar = list(tugas or [])
    draf["jadwal"] = [{"jam": slot[i % len(slot)],
                       "tugas": t.get("judul", "?") if isinstance(t, dict) else str(t),
                       "penanggung_jawab": t.get("penanggung_jawab", "belum ditentukan") if isinstance(t, dict) else "belum ditentukan"}
                      for i, t in enumerate(daftar)]
    draf["catatan"] = "Jadwal DRAF — agent pasif; Muse yang menjalankan. Slot kosong berarti belum ada tugas."
    return draf

