def _angka(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def bandingkan_harga(nama, harga_kita, harga_pesaing, pesaing):
    """Draf perbandingan harga kita vs pesaing. Harga pesaing dari masukan — jangan isi bila tidak ada datanya."""
    draf = _draf_dasar("banding_harga", "Banding harga: {}".format((nama or "").strip() or "?"))
    draf["produk"] = (nama or "").strip()
    draf["pesaing"] = (pesaing or "").strip() or "belum cukup data"
    hk = _angka(harga_kita)
    hp = _angka(harga_pesaing)
    draf["harga_kita"] = hk
    draf["harga_pesaing"] = hp
    if hk is None or hp is None:
        draf["selisih"] = "belum cukup data"
        draf["kesimpulan"] = "belum cukup data — isi dulu harga pesaing dari sumber resmi."
    else:
        draf["selisih"] = hk - hp
        draf["kesimpulan"] = "Lebih murah" if hk < hp else ("Lebih mahal" if hk > hp else "Sama")
    return draf

